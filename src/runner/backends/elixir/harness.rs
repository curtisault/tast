use crate::runner::backends::beam::env;

/// Companion steps file info for generating real library calls instead of stubs.
#[derive(Debug, Clone)]
pub struct CompanionInfo {
    /// Elixir module name (e.g., "HashidsSteps").
    pub module_name: String,
    /// File name relative to the generated test directory (e.g., "hashids_steps.exs").
    pub file_name: String,
}

/// Generate a complete ExUnit test module for a test plan.
///
/// When `companion` is `Some`, generates calls to the companion steps module
/// instead of assertion stubs. When `None`, generates stubs as before.
pub fn generate_exunit_file(plan: &TestPlan, companion: Option<&CompanionInfo>) -> String {
    let module_name = env::generated_module_name(&plan.plan.name);
    let mut out = String::with_capacity(1024);

    out.push_str("Code.require_file(\"tast_helper.exs\", __DIR__)\n");
    if let Some(info) = companion {
        out.push_str(&format!(
            "Code.require_file(\"{}\", __DIR__)\n",
            info.file_name
        ));
    }
    out.push('\n');
    out.push_str(&format!("defmodule {module_name}Test do\n"));
    out.push_str("  use ExUnit.Case\n\n");
    out.push_str(&format!(
        "  @moduledoc \"\"\"\n  Auto-generated by TAST. Do not edit.\n\n  Plan: {}\n  \"\"\"\n\n",
        plan.plan.name
    ));
    out.push_str("  @moduletag :tast_generated\n");

    for step in &plan.steps {
        out.push('\n');
        if let Some(info) = companion {
            out.push_str(&generate_companion_test_block(step, &info.module_name));
        } else {
            out.push_str(&generate_test_block(step));
        }
    }

    out.push_str("end\n");
    out
}

/// Generate a test block that delegates to a companion steps module.
pub fn generate_companion_test_block(step: &PlanStep, module_name: &str) -> String {
    let node_name = &step.node;
    let description = step
        .description
        .as_deref()
        .unwrap_or("test step")
        .to_lowercase();
    let function_name = env::to_beam_name(node_name);

    let mut out = String::with_capacity(512);

    out.push_str(&format!("  describe \"{node_name}\" do\n"));
    out.push_str(&format!("    test \"{description}\" do\n"));

    // Build inputs map from upstream step outputs.
    if step.inputs.is_empty() {
        out.push_str("      inputs = %{}\n");
    } else {
        out.push_str("      inputs = %{\n");
        for (i, input) in step.inputs.iter().enumerate() {
            let comma = if i < step.inputs.len() - 1 { "," } else { "" };
            out.push_str(&format!(
                "        \"{}\" => TastHelper.tast_input(\"{}\"){}\n",
                input.field, input.field, comma
            ));
        }
        out.push_str("      }\n");
    }

    out.push_str(&format!(
        "      outputs = {module_name}.{function_name}(inputs)\n"
    ));
    out.push_str("      if outputs != %{}, do: TastHelper.tast_output(outputs)\n");

    out.push_str("    end\n");
    out.push_str("  end\n");
    out
}

/// Generate a single ExUnit test block for a plan step.
pub fn generate_test_block(step: &PlanStep) -> String {
    let node_name = &step.node;
    let description = step
        .description
        .as_deref()
        .unwrap_or("test step")
        .to_lowercase();

    let mut out = String::with_capacity(512);

    out.push_str(&format!("  describe \"{node_name}\" do\n"));
    out.push_str(&format!("    test \"{description}\" do\n"));

    // Input reads from upstream steps.
    if !step.inputs.is_empty() {
        out.push_str("      # --- Inputs ---\n");
        for input in &step.inputs {
            out.push_str(&format!(
                "      {} = TastHelper.tast_input(\"{}\")\n",
                input.field, input.field
            ));
        }
        out.push('\n');
    }

    // Preconditions (given).
    for entry in &step.preconditions {
        out.push_str(&format!(
            "      # --- {} ---\n",
            capitalize_step_type(&entry.step_type)
        ));
        out.push_str(&format!("      # {}\n", entry.text));

        if !entry.data.is_empty() {
            out.push_str(&generate_data_setup(&entry.data));
        }

        out.push('\n');
    }

    // Actions (when).
    for entry in &step.actions {
        out.push_str(&format!(
            "      # --- {} ---\n",
            capitalize_step_type(&entry.step_type)
        ));
        out.push_str(&format!("      # {}\n\n", entry.text));
    }

    // Assertions (then/and/but).
    for entry in &step.assertions {
        out.push_str(&format!(
            "      # --- {} ---\n",
            capitalize_step_type(&entry.step_type)
        ));
        out.push_str(&format!("      # {}\n", entry.text));
        out.push_str(&format!(
            "      assert true, \"{}\"\n\n",
            elixir_escape(&entry.text)
        ));
    }

    // Output wiring.
    if !step.outputs.is_empty() {
        out.push_str("      # --- Output ---\n");

        // Bind placeholder values for output fields not already bound from inputs.
        let input_fields: Vec<&str> = step.inputs.iter().map(|i| i.field.as_str()).collect();
        for field in &step.outputs {
            if !input_fields.contains(&field.as_str()) {
                out.push_str(&format!("      {field} = \"tast:{field}\"\n"));
            }
        }

        let fields: Vec<String> = step.outputs.iter().map(|f| format!("{f}: {f}")).collect();
        out.push_str(&format!(
            "      TastHelper.tast_output(%{{{}}})\n",
            fields.join(", ")
        ));
        out.push('\n');
    }

    out.push_str("    end\n");
    out.push_str("  end\n");
    out
}

/// Generate the TastHelper module with TAST_OUTPUT/TAST_INPUT utilities.
pub fn generate_helper_module() -> String {
    r##"defmodule TastHelper do
  @moduledoc """
  Auto-generated by TAST. Do not edit.

  Provides I/O helpers for passing data between test steps.
  Outputs are written to :standard_error to bypass ExUnit IO capture.
  Uses a zero-dependency JSON encoder so projects don't need Jason.
  """

  def tast_output(data) when is_map(data) do
    json = encode_json(data)
    # Write to :standard_error to bypass ExUnit IO capture.
    IO.puts(:standard_error, "TAST_OUTPUT:#{json}")
  end

  def tast_input(key) do
    System.get_env("TAST_INPUT_#{String.upcase(to_string(key))}")
  end

  defp encode_json(map) when is_map(map) do
    pairs =
      Enum.map_join(map, ",", fn {k, v} ->
        "#{encode_json_value(k)}:#{encode_json_value(v)}"
      end)

    "{#{pairs}}"
  end

  defp encode_json_value(val) when is_binary(val) do
    escaped = val |> String.replace("\\", "\\\\") |> String.replace("\"", "\\\"")
    "\"#{escaped}\""
  end

  defp encode_json_value(val) when is_atom(val), do: encode_json_value(Atom.to_string(val))
  defp encode_json_value(val) when is_number(val), do: "#{val}"
  defp encode_json_value(val), do: encode_json_value(to_string(val))
end
"##
    .to_owned()
}

/// Generate Elixir data setup code from step data fields.
///
/// Produces an Elixir map assignment like:
/// ```elixir
/// data = %{
///   email: "test@example.com",
///   password: "secure123"
/// }
/// ```
pub fn generate_data_setup(data: &[(String, String)]) -> String {
    if data.is_empty() {
        return String::new();
    }

    let mut out = String::new();
    out.push_str("      data = %{\n");
    for (i, (key, value)) in data.iter().enumerate() {
        let escaped = elixir_escape(value);
        let comma = if i < data.len() - 1 { "," } else { "" };
        out.push_str(&format!("        {key}: \"{escaped}\"{comma}\n"));
    }
    out.push_str("      }\n");
    out
}

/// Generate input reading code from resolved input field names.
pub fn generate_input_reads(inputs: &[String]) -> String {
    let mut out = String::new();
    for input in inputs {
        out.push_str(&format!(
            "      {input} = TastHelper.tast_input(\"{input}\")\n"
        ));
    }
    out
}

/// Escape a string for safe embedding in an Elixir double-quoted string.
pub fn elixir_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '#' => out.push_str("\\#"), // Prevent interpolation injection.
            _ => out.push(ch),
        }
    }
    out
}

fn capitalize_step_type(step_type: &str) -> String {
    let mut chars = step_type.chars();
    match chars.next() {
        None => String::new(),
        Some(c) => c.to_uppercase().to_string() + chars.as_str(),
    }
}

